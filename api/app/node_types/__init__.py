"""Node type registry: each `kind` has its own Pydantic schema for `props` (ADR 0013)."""

from typing import Annotated, Any, Literal, NamedTuple

from pydantic import BaseModel, ConfigDict, Field, StringConstraints, model_validator

DEFAULT_KIND = "idea"

CHECKLIST_MAX_ITEMS = 30
ITEM_TEXT_MAX_LENGTH = 100
ITEM_ID_MAX_LENGTH = 64

TaskStatus = Literal["to_do", "in_progress", "done"]
DEFAULT_TASK_STATUS: TaskStatus = "to_do"


class IdeaProps(BaseModel):
    """An idea has no data of its own yet besides the title."""

    model_config = ConfigDict(extra="forbid")


class ChecklistItem(BaseModel):
    """One line of a task's checklist (slice 4A, decision D4).

    `id` is generated by the client and opaque to the API: the whole `props` is replaced on each
    save, so the only rule is that ids do not repeat within a checklist.
    """

    model_config = ConfigDict(extra="forbid")

    id: Annotated[
        str, StringConstraints(strip_whitespace=True, min_length=1, max_length=ITEM_ID_MAX_LENGTH)
    ]
    text: Annotated[
        str,
        StringConstraints(strip_whitespace=True, min_length=1, max_length=ITEM_TEXT_MAX_LENGTH),
    ]
    done: bool = False


class TaskProps(BaseModel):
    """A task's own data: where it stands and what it is made of (slice 4A, decision D1).

    Status and checklist are independent (decision D7): completing every item does not make the
    task `done`, and `done` does not check the items.
    """

    model_config = ConfigDict(extra="forbid")

    status: TaskStatus = DEFAULT_TASK_STATUS
    checklist: Annotated[list[ChecklistItem], Field(max_length=CHECKLIST_MAX_ITEMS)] = Field(
        default_factory=list
    )

    @model_validator(mode="after")
    def check_unique_item_ids(self) -> "TaskProps":
        ids = [item.id for item in self.checklist]
        if len(set(ids)) != len(ids):
            raise ValueError("checklist item ids must be unique")
        return self


class NodeType(NamedTuple):
    """What the API knows about a kind: how to validate its props and whether it nests."""

    schema: type[BaseModel]
    allows_children: bool


NODE_TYPES: dict[str, NodeType] = {
    "idea": NodeType(IdeaProps, allows_children=True),
    # A task is a leaf: it holds a checklist, not other nodes (slice 4A, decision D3).
    "task": NodeType(TaskProps, allows_children=False),
}


class UnknownNodeKind(ValueError):
    pass


def is_known_kind(kind: str) -> bool:
    return kind in NODE_TYPES


def allows_children(kind: str) -> bool:
    """Whether a node of this kind can be a parent. An unknown kind never can."""
    node_type = NODE_TYPES.get(kind)
    return node_type is not None and node_type.allows_children


def validate_props(kind: str, props: dict[str, Any]) -> dict[str, Any]:
    """Validates `props` with the kind's schema; raises `UnknownNodeKind` or `ValidationError`."""
    node_type = NODE_TYPES.get(kind)
    if node_type is None:
        raise UnknownNodeKind(f"unknown node kind: {kind}")
    return node_type.schema.model_validate(props).model_dump(mode="json")
